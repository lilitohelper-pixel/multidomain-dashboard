// Translates a single category node name for display. Unknown names (custom
// user-created Savings goals, for instance) pass through unchanged — they're
// free text the user typed themselves, not part of the fixed matrix.
export function translateCategoryName(lang, name) {
  return categoryNameTranslations[lang]?.[name] || name;
}

export function t(lang, key, vars = {}) {
  const dict = dictionaries[lang] || dictionaries.en;
  let str = dict[key] ?? dictionaries.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.split(`{${k}}`).join(v);
  }
  return str;
}

